/// 投稿画面の「送信時の設定」を狭い幅へ詰めるための取り決め (#1167・案 B)。
///
/// ## なぜ要るか
///
/// #1167 の案 3+2 で、送信時の設定（公開範囲 / ローカルのみ / 言語 / 引用許可）を
/// アイコン列とは**別の行**へ出した。⚠⚠ **ところが iPhone 13 mini（375pt）では
/// その行自体が折り返して、下のツールバーが 3 段になった**（2026-09-28 実測）。
/// 1.x で投稿フォームの高さを節約してきた分が丸ごと失われる。
///
/// 案 B（2026-09-28 pooza 決定）は **狭い幅では設定をアイコン列の右端に固定して
/// 1 段にまとめる**。⚠ **守る条件は変えない** —— 送信時の設定は畳まない
/// （見えないまま効いている状態は #1167 の元の不具合そのもの）。畳むのはアイコンだけ。
library;

/// 送信時の設定をラベル付きの別行に出す下限の幅（論理 px）。
///
/// これを**下回ると 1 段**（設定を詰めてアイコン列の右端へ固定）、**上回ると 2 段**
/// （今までどおりラベル付きで別行）。
///
/// ⚠ **値の出どころ**（2026-09-29 の見積り・テキストスケール 1.0）:
///
/// | 幅を食うもの | Mastodon の最悪ケース |
/// | --- | --- |
/// | 公開範囲（アイコン + 「ひかえめな公開」+ 矢印） | 約 135 |
/// | 言語（「日本語」+ 矢印） | 約 80 |
/// | 引用許可（アイコン + 「フォロワーのみ」+ 矢印） | 約 135 |
/// | 間隔 | 16 |
///
/// 合計 **約 330**。⚠ **560 はその 1.7 倍**にしてあり、テキストスケール 1.3
/// （330 × 1.3 ≒ 430）でも 2 段目が折り返さない。
///
/// ⚠ **デスクトップの狭幅運用を 1 段側へ落とさないための下限でもある。**
/// capsicum は動画と横並びで使われるので 630px 前後のウィンドウが常態で
/// （`project_desktop_split_screen_usage`）、**そこは 2 段のままがよい**と
/// 2026-09-28 の Linux 実測で確認済み。560 なら 630 は 2 段側に残る。
///
/// ⚠ **分岐軸はプラットフォームではなく画面幅**（docs/CLAUDE.md デスクトップ対応）。
/// `kOverlayLayerPanelMinWidth` と同じ流儀の、文書化された境目。
const double kComposeToolbarTwoRowMinWidth = 560;

/// 1 段のときにアイコン列へ必ず残す幅（論理 px）。
///
/// ⚠⚠ **「…」1 個ぶんを確保する。**設定が伸びきってアイコン列が 0 幅になると、
/// **畳まれたアイコンを開く手段が無くなる**（全部が「…」の中にあるのに「…」が
/// 出せない）。`OverflowIconRow` の `itemExtent` 既定値と揃えてある。
const double kComposeToolbarMinIconRowWidth = 40;

/// 狭い幅で出す設定ラベル。**5 文字まではそのまま、超えたら先頭 4 文字 + `…`**。
///
/// ⚠⚠ **略語を作らない**（2026-09-29 pooza 決定）。`docs/CLAUDE.md` の用語統一表が
/// 正本で、「ひかえめな公開」を「ひかえめ」と呼ぶような**短縮形を発明すると
/// 用語が二重管理になる**。機械的に省略記号で切るぶんには新しい語が生まれない。
///
/// ⚠ **ドロップダウンを開いたときの選択肢はフルラベルのまま。**詰めるのは
/// 閉じているボタンの表示だけなので、選ぶときは必ず正式な名前が見える。
///
/// この規則での実際の見え方:
///
/// | 元 | 詰めた形 |
/// | --- | --- |
/// | 公開 / ホーム / 指名 | そのまま |
/// | フォロワー / パブリック（5 文字） | そのまま |
/// | ひかえめな公開（7 文字） | ひかえめ… |
/// | 非公開の返信（6 文字） | 非公開の… |
///
/// ⚠ **Misskey の公開範囲は全部 5 文字以内なので、詰めても何も変わらない。**
/// 影響を受けるのは Mastodon の 2 つだけ。
String compactSettingLabel(String label) {
  // ⚠ `characters` ではなく素の `length` で数えると、絵文字や結合文字を含む
  // ラベルが途中で割れる。ここへ来るのは日本語だけだが、規則としては書記素で数える。
  final graphemes = label.runes.toList();
  if (graphemes.length <= _compactLabelMaxLength) return label;
  final kept = String.fromCharCodes(graphemes.take(_compactLabelKeepLength));
  return '$kept…';
}

/// そのまま出す上限の文字数。
const int _compactLabelMaxLength = 5;

/// 超えたときに残す文字数（残り 1 文字は `…` が使う）。
const int _compactLabelKeepLength = 4;

/// 狭い幅で出す引用許可の値 (#1167・2026-09-29 pooza 決定)。
///
/// ⚠ 公開範囲とは詰め方が違う（あちらは機械的な省略、ここは**値の短縮**）。
/// 引用許可は選択肢が 3 つで固定され、「のみ」を落としても意味が変わらないため。
/// ⚠ **キーは `_quoteApprovalLabels` と 1 対 1**。片方だけ足すと詰めた側が欠ける。
const composeQuoteApprovalShortLabels = {
  'public': '誰でも',
  'followers': 'フォロワー',
  'nobody': '許可しない',
};
